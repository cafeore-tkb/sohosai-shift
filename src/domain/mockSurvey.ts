const hh = (h: string) => `${h.padStart(2, "0")}:00`;

/** 試用データのアンケート回答 CSV（BOM つき、改行は LF、末尾に改行なし。サンプルと同じ形式） */
export function mockSurveyCsv(): string {
  const rows: string[][] = [[...MOCK_SURVEY_HEADERS]];
  for (const [name, status, stores, ice, car, wants, dislikes, workload, ...days] of MOCK_ROWS)
    days.forEach((spans, i) =>
      spans
        .split(" ")
        .filter(Boolean)
        .forEach((span) => {
          const [from, to] = span.split("-");
          rows.push([name, status, stores, ice, car, wants, dislikes, workload, MOCK_DATES[i], hh(from), hh(to)]);
        }),
    );
  return "\ufeff" + rows.map(csvLine).join("\n");
}

